-- In-app chat between a client and the courier assigned to their order.
CREATE TABLE public.order_messages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id text NOT NULL REFERENCES public.branches(id),
  order_id text NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  sender_id text NOT NULL,
  sender_role text NOT NULL CHECK (sender_role IN ('client','courier')),
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 500),
  created_at double precision NOT NULL,
  read smallint NOT NULL DEFAULT 0 CHECK (read IN (0, 1))
);
CREATE INDEX order_messages_order_idx ON public.order_messages(order_id, id);

CREATE TRIGGER order_messages_branch_guard BEFORE INSERT OR UPDATE OF branch_id ON public.order_messages
FOR EACH ROW EXECUTE FUNCTION public.gk_assign_branch();

ALTER TABLE public.order_messages ENABLE ROW LEVEL SECURITY;

-- Only the order's own client and its currently assigned courier can see or write messages.
CREATE POLICY order_messages_select ON public.order_messages FOR SELECT TO gk_api
USING (
  branch_id = public.gk_branch_id()
  AND EXISTS (
    SELECT 1 FROM public.orders o WHERE o.id = order_messages.order_id AND (
      (public.gk_actor_role() = 'client' AND o.client_id = public.gk_actor_id())
      OR (public.gk_actor_role() = 'courier' AND o.courier_id = public.gk_actor_id())
    )
  )
);
CREATE POLICY order_messages_insert ON public.order_messages FOR INSERT TO gk_api
WITH CHECK (
  branch_id = public.gk_branch_id()
  AND sender_id = public.gk_actor_id()
  AND sender_role = public.gk_actor_role()
  AND EXISTS (
    SELECT 1 FROM public.orders o WHERE o.id = order_messages.order_id AND (
      (sender_role = 'client' AND o.client_id = public.gk_actor_id())
      OR (sender_role = 'courier' AND o.courier_id = public.gk_actor_id())
    )
  )
);
CREATE POLICY order_messages_mark_read ON public.order_messages FOR UPDATE TO gk_api
USING (
  branch_id = public.gk_branch_id()
  AND sender_id <> public.gk_actor_id()
  AND EXISTS (
    SELECT 1 FROM public.orders o WHERE o.id = order_messages.order_id AND (
      (public.gk_actor_role() = 'client' AND o.client_id = public.gk_actor_id())
      OR (public.gk_actor_role() = 'courier' AND o.courier_id = public.gk_actor_id())
    )
  )
)
WITH CHECK (branch_id = public.gk_branch_id());

REVOKE ALL ON public.order_messages FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON public.order_messages TO gk_api;
GRANT UPDATE (read) ON public.order_messages TO gk_api;
GRANT USAGE, SELECT ON SEQUENCE public.order_messages_id_seq TO gk_api;

-- Courier name and phone, revealed to the client only while the delivery is active.
CREATE FUNCTION public.gk_order_courier(p_order text) RETURNS TABLE(name text, phone text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public
AS $$
  SELECT u.name, u.phone
  FROM public.orders o JOIN public.users u ON u.id = o.courier_id
  WHERE o.id = p_order
    AND o.client_id = public.gk_actor_id()
    AND o.status IN ('preparing','ready','enroute')
    AND o.dispatch_state = 'assigned'
$$;
REVOKE ALL ON FUNCTION public.gk_order_courier(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.gk_order_courier(text) TO gk_api;
